CREATE TABLE participant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(50) NOT NULL CHECK (btrim(display_name) <> ''),
    birth_year SMALLINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE participant_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id BIGINT NOT NULL REFERENCES participant(id),
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE book (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by BIGINT NOT NULL REFERENCES participant(id),
    title VARCHAR(100) NOT NULL DEFAULT '청춘 교환일기',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE book_participant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES book(id),
    participant_id BIGINT NOT NULL REFERENCES participant(id),
    slot_no SMALLINT NOT NULL CHECK (slot_no IN (1, 2)),
    counterpart_label VARCHAR(30) NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (book_id, participant_id),
    UNIQUE (book_id, slot_no)
);

CREATE INDEX idx_book_participant_participant ON book_participant(participant_id, book_id);

CREATE TABLE book_invitation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES book(id),
    issued_by BIGINT NOT NULL,
    accepted_by BIGINT,
    code VARCHAR(32) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (book_id, issued_by) REFERENCES book_participant(book_id, participant_id),
    FOREIGN KEY (book_id, accepted_by) REFERENCES book_participant(book_id, participant_id),
    CHECK ((accepted_by IS NULL) = (accepted_at IS NULL)),
    CHECK (accepted_by IS NULL OR accepted_by <> issued_by)
);
