CREATE TABLE chapter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES book(id),
    name VARCHAR(100) NOT NULL CHECK (btrim(name) <> ''),
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    opened_at TIMESTAMPTZ,
    FOREIGN KEY (book_id, created_by) REFERENCES book_participant(book_id, participant_id)
);

CREATE INDEX idx_chapter_book ON chapter(book_id, id);

CREATE TABLE story (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id BIGINT NOT NULL REFERENCES chapter(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES participant(id),
    title VARCHAR(200) NOT NULL DEFAULT '',
    content TEXT NOT NULL DEFAULT '',
    mission_instruction TEXT NOT NULL DEFAULT '',
    completed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (chapter_id, author_id),
    CHECK (completed_at IS NULL OR
        (btrim(title) <> '' AND btrim(content) <> '' AND btrim(mission_instruction) <> ''))
);

-- The first membership is created in the book creation transaction.
-- Backfill older books and create the same default chapter for new books.
INSERT INTO chapter(book_id, name, created_by)
SELECT b.id, '초등학생 시절', b.created_by FROM book b;

CREATE FUNCTION create_default_chapter() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.slot_no = 1 THEN
        INSERT INTO chapter(book_id, name, created_by)
        VALUES (NEW.book_id, '초등학생 시절', NEW.participant_id);
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER book_first_participant_chapter
AFTER INSERT ON book_participant
FOR EACH ROW EXECUTE FUNCTION create_default_chapter();
